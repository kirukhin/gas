// components/product/ProductDescription.jsx

/*
    ProductDescription

    Основной текстовый блок карточки товара.

    Его задачи:

    • дать поисковым системам большой объём
      уникального тематического текста;

    • объяснить инженеру,
      что представляет собой оборудование;

    • объединить данные:

        product
        line
        type

    в одну логичную статью.

*/


import ProductSection from './ProductSection'


export default function ProductDescription({

    product,

    type

}) {

    if (!product) return null


    const {

        commonSpecs = {},

        specs = {}

    } = product



    return (

        <ProductSection

            title={`Описание ${product.model}`}

            subtitle="Техническое описание оборудования"

        >

            <div
                className="
                    mx-auto
                    max-w-5xl
                    space-y-8
                    text-lg
                    leading-8
                    text-gray-700
                "
            >

                {/* =====================================================
                    Введение
                ====================================================== */}

                <p>

                    <strong>{product.name}</strong> представляет собой современный{' '}

                    <strong>

                        {commonSpecs.technology}

                    </strong>{' '}

                    осушитель воздуха серии{' '}

                    <strong>

                        {product.lineTitle}

                    </strong>,

                    предназначенный для подготовки сжатого воздуха
                    промышленного качества.

                    Модель обеспечивает производительность до{' '}

                    <strong>

                        {specs.flow} м³/мин

                    </strong>

                    при сохранении стабильных рабочих характеристик
                    во всём расчетном диапазоне эксплуатации.

                </p>



                {/* =====================================================
                    Технология
                ====================================================== */}

                <p>

                    В основе работы оборудования используется{' '}

                    <strong>

                        {commonSpecs.technology}

                    </strong>{' '}

                    технология осушки с{' '}

                    <strong>

                        {commonSpecs.regeneration}

                    </strong>{' '}

                    регенерацией.

                    Такое решение позволяет получать
                    сжатый воздух с точкой росы до{' '}

                    <strong>

                        {commonSpecs.dewPoint} °C

                    </strong>

                    при высокой надежности,
                    простоте обслуживания
                    и длительном сроке службы оборудования.

                </p>



                {/* =====================================================
                    Область применения
                ====================================================== */}

                <p>

                    Осушитель применяется
                    в системах подготовки сжатого воздуха,
                    где предъявляются повышенные требования
                    к содержанию влаги,
                    стабильности параметров
                    и качеству воздуха.

                    Оборудование подходит
                    для эксплуатации
                    в составе компрессорных станций,
                    технологических линий,
                    генераторов азота,
                    генераторов кислорода,
                    лазерных комплексов,
                    покрасочных производств
                    и другого промышленного оборудования.

                </p>



                {/* =====================================================
                    Рабочие характеристики
                ====================================================== */}

                <p>

                    Конструкция оборудования рассчитана
                    на работу при давлении{' '}

                    <strong>

                        {commonSpecs.pressureMin}–{commonSpecs.pressureMax} бар

                    </strong>

                    и температуре входящего воздуха{' '}

                    <strong>

                        {commonSpecs.airTemperature} °C

                    </strong>.

                    Благодаря небольшим потерям давления
                    порядка{' '}

                    <strong>

                        {commonSpecs.pressureDrop} бар

                    </strong>

                    осушитель практически
                    не оказывает влияния
                    на эффективность компрессорной системы.

                </p>



                {/* =====================================================
                    Качество воздуха
                ====================================================== */}

                <p>

                    После прохождения через систему подготовки
                    воздух соответствует требованиям{' '}

                    <strong>

                        {commonSpecs.purityClass}

                    </strong>.

                    Это позволяет использовать оборудование
                    в технологических процессах,
                    чувствительных к наличию влаги,
                    масла и загрязнений,
                    включая производство электроники,
                    фармацевтики,
                    пищевой промышленности
                    и высокоточных производств.

                </p>



                {/* =====================================================
                    Управление
                ====================================================== */}

                <p>

                    Управление осуществляется системой{' '}

                    <strong>

                        {commonSpecs.control}

                    </strong>,

                    которая автоматически контролирует
                    рабочие циклы,
                    обеспечивает своевременную регенерацию,
                    контролирует температурные параметры
                    и поддерживает стабильную работу оборудования
                    без постоянного вмешательства оператора.

                </p>



                {/* =====================================================
                    Итог
                ====================================================== */}

                <p>

                    Благодаря сочетанию высокой надежности,
                    энергоэффективности,
                    компактных размеров
                    и современной системы управления,

                    <strong>

                        {' '}{product.model}

                    </strong>

                    является эффективным решением
                    для подготовки сжатого воздуха
                    в промышленных системах,
                    где требуется стабильное качество воздуха
                    и длительная бесперебойная эксплуатация оборудования.

                </p>



                {/* =====================================================
                    Дополнительная информация из страницы категории
                ====================================================== */}

                {type?.intro?.content?.length > 0 && (

                    <div
                        className="
                            rounded-2xl
                            border
                            border-red-100
                            bg-red-50
                            p-8
                        "
                    >

                        <h3
                            className="
                                text-2xl
                                font-bold
                                text-gray-900
                            "
                        >

                            {type.intro.title}

                        </h3>

                        <div
                            className="
                                mt-6
                                space-y-5
                            "
                        >

                            {type.intro.content.map((paragraph) => (

                                <p key={paragraph}>

                                    {paragraph}

                                </p>

                            ))}

                        </div>

                    </div>

                )}

            </div>

        </ProductSection>

    )

}